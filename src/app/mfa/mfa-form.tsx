"use client";

import { useEffect, useState } from "react";
import { Alert, Button, Field, Input } from "@/components/ui";
import { createBrowserSupabase } from "@/lib/supabase/client";
import { recordMfaResult } from "./actions";

type Step = { kind: "loading" } | { kind: "enroll"; factorId: string; qr: string; secret: string } | { kind: "verify"; factorId: string } | { kind: "error"; message: string };

/** Enrol an authenticator app (first time) or enter the current code (every sign-in). */
export function MfaForm({ next, email }: { next: string; email: string }) {
  const [step, setStep] = useState<Step>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    const supabase = createBrowserSupabase();
    (async () => {
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (error) return setStep({ kind: "error", message: error.message });
      const verified = data.totp.find((f) => f.status === "verified");
      if (verified) return setStep({ kind: "verify", factorId: verified.id });
      // Remove half-finished enrolments so a fresh QR code can be shown.
      for (const f of data.all.filter((f) => f.factor_type === "totp" && f.status !== "verified")) {
        await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
      const { data: enrolled, error: enrollError } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: `JD Foods OS ${new Date().toISOString().slice(0, 10)}`,
        issuer: "JD Foods OS",
      });
      if (enrollError || !enrolled) return setStep({ kind: "error", message: enrollError?.message ?? "Couldn't start setup." });
      setStep({ kind: "enroll", factorId: enrolled.id, qr: enrolled.totp.qr_code, secret: enrolled.totp.secret });
    })();
  }, []);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (step.kind !== "enroll" && step.kind !== "verify") return;
    setBusy(true);
    setError("");
    const supabase = createBrowserSupabase();
    const { data: challenge, error: chErr } = await supabase.auth.mfa.challenge({ factorId: step.factorId });
    if (chErr || !challenge) {
      setBusy(false);
      return setError(chErr?.message ?? "Couldn't check the code. Try again.");
    }
    const { error: vErr } = await supabase.auth.mfa.verify({ factorId: step.factorId, challengeId: challenge.id, code: code.trim() });
    await recordMfaResult(!vErr, step.kind === "enroll");
    if (vErr) {
      setBusy(false);
      setCode("");
      return setError("That code didn't work. Check the time on your phone is correct and enter the newest code.");
    }
    window.location.href = next;
  }

  if (step.kind === "loading") return <p className="text-sm text-muted-foreground">Loading…</p>;
  if (step.kind === "error") return <Alert tone="danger">{step.message}</Alert>;

  return (
    <form onSubmit={submit} className="space-y-4">
      {step.kind === "enroll" && (
        <div className="space-y-3 text-sm">
          <p>
            <strong>Set up once:</strong> open your authenticator app, add an account, and scan this code.
          </p>
          {/* qr_code is an SVG data URL generated by Supabase */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={step.qr} alt="QR code for your authenticator app" className="mx-auto size-48 rounded bg-white p-2" />
          <details>
            <summary className="cursor-pointer text-muted-foreground">Can&apos;t scan? Enter this key instead</summary>
            <p className="mt-1 break-all rounded bg-muted p-2 font-mono text-xs">{step.secret}</p>
            <p className="mt-1 text-xs text-muted-foreground">Account: {email}</p>
          </details>
        </div>
      )}
      <Field label="6-digit code from your app" htmlFor="code">
        <Input
          id="code"
          value={code}
          onChange={(e) => setCode(e.target.value.replace(/\D/g, "").slice(0, 6))}
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="\d{6}"
          required
          autoFocus
        />
      </Field>
      {error && <Alert tone="danger">{error}</Alert>}
      <Button type="submit" disabled={busy || code.length !== 6} className="w-full">
        {busy ? "Checking…" : step.kind === "enroll" ? "Finish setup" : "Continue"}
      </Button>
      {step.kind === "verify" && (
        <p className="text-xs text-muted-foreground">Lost your phone? Ask an administrator to reset your two-step sign-in.</p>
      )}
    </form>
  );
}
